CREATE TABLE LA_ACCOUNT (
    ID BINARY(16) NOT NULL,
    CURRENCY CHAR(3) NOT NULL,
    OVERDRAFT_LIMIT_MINOR BIGINT NOT NULL DEFAULT 0,
    BALANCE_MINOR BIGINT NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (ID),
    CONSTRAINT CK_LA_ACCOUNT_OVERDRAFT_NONNEGATIVE CHECK (OVERDRAFT_LIMIT_MINOR >= 0),
    CONSTRAINT CK_LA_ACCOUNT_CURRENCY CHECK (CURRENCY IN ('EUR', 'USD', 'JPY'))
);

CREATE TABLE LA_TRANSACTION (
    ID BINARY(16) NOT NULL,
    DESCRIPTION VARCHAR(500) NOT NULL,
    RECORDED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    REVERSAL_OF_ID BINARY(16) NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UQ_LA_TRANSACTION_REVERSAL UNIQUE (REVERSAL_OF_ID),
    CONSTRAINT FK_LA_TRANSACTION_REVERSAL FOREIGN KEY (REVERSAL_OF_ID) REFERENCES LA_TRANSACTION (ID)
);

CREATE TABLE LA_ENTRY (
    ID BINARY(16) NOT NULL,
    TRANSACTION_ID BINARY(16) NOT NULL,
    ACCOUNT_ID BINARY(16) NOT NULL,
    DIRECTION VARCHAR(6) NOT NULL,
    AMOUNT_MINOR BIGINT NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT CK_LA_ENTRY_DIRECTION CHECK (DIRECTION IN ('DEBIT', 'CREDIT')) ,
    CONSTRAINT CK_LA_ENTRY_AMOUNT_POSITIVE CHECK (AMOUNT_MINOR > 0),
    CONSTRAINT FK_LA_ENTRY_TRANSACTION FOREIGN KEY (TRANSACTION_ID) REFERENCES LA_TRANSACTION (ID),
    CONSTRAINT FK_LA_ENTRY_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES LA_ACCOUNT (ID),
    INDEX IX_LA_ENTRY_ACCOUNT (ACCOUNT_ID),
    INDEX IX_LA_ENTRY_TRANSACTION (TRANSACTION_ID)
);

CREATE TABLE LA_IDEMPOTENCY_RECORD (
    ID BINARY(16) NOT NULL,
    SCOPE VARCHAR(32) NOT NULL,
    IDEMPOTENCY_KEY VARCHAR(255) NOT NULL,
    REQUEST_HASH CHAR(64) NOT NULL,
    RESOURCE_ID BINARY(16) NULL,
    RESPONSE_BODY JSON NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (ID),
    CONSTRAINT UQ_LA_IDEMPOTENCY_SCOPE_KEY UNIQUE (SCOPE, IDEMPOTENCY_KEY),
    INDEX IX_LA_IDEMPOTENCY_RESOURCE (RESOURCE_ID)
);
